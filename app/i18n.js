function t(key, ...params) {
  const template = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\d+)\}/g, (m, i) => (params[i] ?? m));
}

/** A text that says a count: the key's ".one" form for 1, its ".other" form for the rest. */
const tn = (key, n, ...params) => t(`${key}.${n === 1 ? 'one' : 'other'}`, n, ...params);

/** "a, b and c", in the interface language; joiner is "and" or "or". */
function list(items, joiner) {
  const words = items.map(String);
  return words.length < 2 ? words.join('') : `${words.slice(0, -1).join(', ')} ${t(joiner)} ${words[words.length - 1]}`;
}

/** A file's name as an error message starts with it, or "That file". */
const fileLabel = name => (name ? t('file.named', name) : t('file.that'));

// The English of each translated element, kept from the page as it was first loaded.
const originals = new WeakMap();
const ATTRIBUTES = [['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle'], ['placeholder', 'i18nPlaceholder']];

function original(el, what) {
  let kept = originals.get(el);
  if (!kept) originals.set(el, kept = {});
  if (!(what in kept)) kept[what] = what === 'html' ? el.innerHTML : el.getAttribute(what);
  return kept[what];
}

/** Puts the page's own texts in the interface language. Translations are this file's constants, never data. */
function translatePage(doc) {
  doc.documentElement.lang = current;
  for (const el of doc.querySelectorAll('[data-i18n]')) {
    const english = original(el, 'html');
    el.innerHTML = current === 'es' ? PAGE_ES[el.dataset.i18n] ?? english : english;
  }
  for (const [attribute, key] of ATTRIBUTES) {
    for (const el of doc.querySelectorAll(`[data-i18n-${attribute}]`)) {
      const english = original(el, attribute);
      el.setAttribute(attribute, current === 'es' ? PAGE_ES[el.dataset[key]] ?? english : english);
    }
  }
}

return { STRINGS, PAGE_ES, setLang, lang, langForBrowser, t, tn, list, fileLabel, translatePage };
