let current = 'en';

function setLang(value) {
  current = value === 'es' ? 'es' : 'en';
  return current;
}

const lang = () => current;

/** The first of the browser's languages that the app speaks, "es" or "en"; English when it speaks none of them. */
function langForBrowser(languages) {
  for (const tag of languages || []) {
    const primary = String(tag).toLowerCase().split('-')[0];
    if (primary === 'es' || primary === 'en') return primary;
  }
  return 'en';
}

